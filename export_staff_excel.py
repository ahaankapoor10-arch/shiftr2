"""Build data/Shiftr_Staff_Availability_Oct2026.xlsx from the generated CSVs.

Run generate_staff_data.py first. Uses openpyxl (installed on the ManSci VM).
Lookups, the availability grid and the coverage check are Excel formulas, so
editing an input (e.g. a wage or an availability 1/0) updates the workbook.
"""

import csv
from datetime import date
from pathlib import Path

from openpyxl import Workbook
from openpyxl.formatting.rule import CellIsRule, FormulaRule
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter

DATA_DIR = Path(__file__).resolve().parent.parent / "data"
OUT_FILE = DATA_DIR / "Shiftr_Staff_Availability_Oct2026.xlsx"

FONT = "Arial"
BLUE = Font(name=FONT, color="0000FF")             # hardcoded inputs
GREEN = Font(name=FONT, color="008000")            # links to another sheet
BLACK = Font(name=FONT)
BOLD = Font(name=FONT, bold=True)
HEADER_FONT = Font(name=FONT, bold=True, color="FFFFFF")
HEADER_FILL = PatternFill("solid", fgColor="1F3864")
INPUT_FILL = PatternFill("solid", fgColor="FFFF00")
GREY_FILL = PatternFill("solid", fgColor="D9D9D9")
RED_FILL = PatternFill("solid", fgColor="F4B6B6")
AMBER_FILL = PatternFill("solid", fgColor="FCE4A8")
GREEN_FILL = PatternFill("solid", fgColor="C6E0B4")
BLUE_FILL = PatternFill("solid", fgColor="BDD7EE")
THIN = Side(style="thin", color="BFBFBF")
BOX = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)


def read_csv(name):
    with (DATA_DIR / name).open(encoding="utf-8") as f:
        return list(csv.DictReader(f))


def header(ws, row, labels, widths=None):
    for col, label in enumerate(labels, start=1):
        c = ws.cell(row=row, column=col, value=label)
        c.font, c.fill, c.border = HEADER_FONT, HEADER_FILL, BOX
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        if widths:
            ws.column_dimensions[get_column_letter(col)].width = widths[col - 1]


def put(ws, row, col, value, font=BLACK, fmt=None, fill=None):
    c = ws.cell(row=row, column=col, value=value)
    c.font, c.border = font, BOX
    if fmt:
        c.number_format = fmt
    if fill:
        c.fill = fill
    return c


