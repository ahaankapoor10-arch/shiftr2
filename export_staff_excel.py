def build_staff(wb, staff, n_avail_rows):
    ws = wb.create_sheet("Staff")
    header(ws, 1, ["staff_id", "first_name", "job_title", "role", "seniority", "contract",
                   "hourly_wage_gbp", "max_weekly_hours", "preferred_block",
                   "Oct available paid hours", "Oct max hours (weekly x 31/7)"],
           [10, 12, 22, 16, 11, 12, 15, 15, 15, 18, 20])
    last = n_avail_rows + 1
    for r, s in enumerate(staff, start=2):
        put(ws, r, 1, s["staff_id"], BLUE)
        put(ws, r, 2, s["first_name"], BLUE)
        put(ws, r, 3, s["job_title"], BLUE)
        put(ws, r, 4, s["role"], BLUE)
        put(ws, r, 5, s["seniority"], BLUE)
        put(ws, r, 6, s["contract"], BLUE)
        put(ws, r, 7, float(s["hourly_wage_gbp"]), BLUE, '"£"#,##0.00')
        put(ws, r, 8, int(s["max_weekly_hours"]), BLUE)
        put(ws, r, 9, s["preferred_block"], BLUE)
        put(ws, r, 10, f"=SUMIFS(Availability!$J$2:$J${last},Availability!$A$2:$A${last},A{r},"
                      f"Availability!$K$2:$K${last},1)", GREEN, "0")
        put(ws, r, 11, f"=ROUND(H{r}*31/7,0)", BLACK, "0")
    ws.cell(row=len(staff) + 3, column=1,
            value="Wages: base pay excl. tronc, ESTIMATES for central London (job adverts); all >= NLW GBP 12.71 "
                  "(GOV.UK, from 1 April 2026). Max weekly hours <= 48 (Working Time Regulations); students <= 20.").font = Font(name=FONT, italic=True)
    ws.freeze_panes = "C2"
    ws.auto_filter.ref = f"A1:K{len(staff) + 1}"


def build_blocks(wb, blocks):
    ws = wb.create_sheet("Shift_Blocks")
    header(ws, 1, ["block", "start", "end", "duration_hours", "unpaid_break_minutes", "paid_hours"],
           [10, 10, 10, 15, 20, 12])
    for r, b in enumerate(blocks, start=2):
        put(ws, r, 1, b["block"], BLUE)
        put(ws, r, 2, b["start"], BLUE)
        put(ws, r, 3, b["end"], BLUE)
        put(ws, r, 4, float(b["duration_hours"]), BLUE, "0.0")
        put(ws, r, 5, int(b["unpaid_break_minutes"]), BLUE)
        put(ws, r, 6, f"=D{r}-E{r}/60", BLACK, "0.0")


def build_availability(wb, rows, n_staff):
    ws = wb.create_sheet("Availability")
    header(ws, 1, ["staff_id", "first_name", "role", "seniority", "date", "weekday",
                   "block", "block_start", "block_end", "paid_hours", "available",
                   "unavailable_reason", "preference"],
           [10, 12, 16, 11, 12, 10, 8, 11, 10, 8, 10, 18, 11])
    s_last = n_staff + 1
    lookup = "INDEX(Staff!${col}$2:${col}${last},MATCH($A{r},Staff!$A$2:$A${last},0))"
    for r, a in enumerate(rows, start=2):
        put(ws, r, 1, a["staff_id"], BLUE)
        put(ws, r, 2, "=" + lookup.format(col="B", last=s_last, r=r), GREEN)
        put(ws, r, 3, "=" + lookup.format(col="D", last=s_last, r=r), GREEN)
        put(ws, r, 4, "=" + lookup.format(col="E", last=s_last, r=r), GREEN)
        put(ws, r, 5, date.fromisoformat(a["date"]), BLUE, "dd-mmm-yyyy")
        put(ws, r, 6, f'=TEXT(E{r},"ddd")', BLACK)
        put(ws, r, 7, a["block"], BLUE)
        put(ws, r, 8, f"=INDEX(Shift_Blocks!$B$2:$B$3,MATCH(G{r},Shift_Blocks!$A$2:$A$3,0))", GREEN)
        put(ws, r, 9, f"=INDEX(Shift_Blocks!$C$2:$C$3,MATCH(G{r},Shift_Blocks!$A$2:$A$3,0))", GREEN)
        put(ws, r, 10, f"=INDEX(Shift_Blocks!$F$2:$F$3,MATCH(G{r},Shift_Blocks!$A$2:$A$3,0))", GREEN)
        put(ws, r, 11, int(a["available"]), BLUE)
        put(ws, r, 12, a["unavailable_reason"] or None, BLUE)
        put(ws, r, 13, int(a["preference"]) if a["preference"] != "" else None, BLUE)
    last = len(rows) + 1
    ws.conditional_formatting.add(f"A2:M{last}", FormulaRule(formula=["$K2=0"], fill=GREY_FILL))
    ws.conditional_formatting.add(f"M2:M{last}", CellIsRule(operator="equal", formula=["1"], fill=GREEN_FILL))
    ws.conditional_formatting.add(f"M2:M{last}", CellIsRule(operator="equal", formula=["-1"], fill=AMBER_FILL))
    ws.freeze_panes = "A2"
    ws.auto_filter.ref = f"A1:M{last}"
    return last


def build_grid(wb, staff, dates, avail_last):
    ws = wb.create_sheet("Availability_Grid")
    ws.cell(row=1, column=1, value="Who can work when: Both / AM / PM / Off (calculated from the Availability sheet)").font = BOLD
    put(ws, 2, 1, "staff_id", HEADER_FONT, fill=HEADER_FILL)
    put(ws, 2, 2, "role", HEADER_FONT, fill=HEADER_FILL)
    ws.column_dimensions["A"].width = 10
    ws.column_dimensions["B"].width = 16
    for j, d in enumerate(dates, start=3):
        c = put(ws, 2, j, d, HEADER_FONT, "ddd dd", HEADER_FILL)
        c.alignment = Alignment(horizontal="center", text_rotation=90)
        ws.column_dimensions[get_column_letter(j)].width = 6
    rng = "Availability!${c}$2:${c}$" + str(avail_last)
    A, E, G, K = (rng.format(c=x) for x in "AEGK")
    for i, s in enumerate(staff, start=3):
        put(ws, i, 1, f"=Staff!A{i - 1}", GREEN)
        put(ws, i, 2, f"=Staff!D{i - 1}", GREEN)
        for j in range(3, 3 + len(dates)):
            col = get_column_letter(j)
            am = f'SUMIFS({K},{A},$A{i},{E},{col}$2,{G},"AM")'
            pm = f'SUMIFS({K},{A},$A{i},{E},{col}$2,{G},"PM")'
            c = put(ws, i, j, f'=CHOOSE(1+{am}+2*{pm},"Off","AM","PM","Both")', GREEN)
            c.alignment = Alignment(horizontal="center")
    area = f"C3:{get_column_letter(2 + len(dates))}{2 + len(staff)}"
    for text, fill in [("Both", GREEN_FILL), ("AM", BLUE_FILL), ("PM", AMBER_FILL), ("Off", GREY_FILL)]:
        ws.conditional_formatting.add(area, CellIsRule(operator="equal", formula=[f'"{text}"'], fill=fill))
    ws.freeze_panes = "C3"


def build_coverage(wb, dates, avail_last):
    ws = wb.create_sheet("Coverage_Check")
    ws.cell(row=1, column=1, value="Available people per role per block vs minimum (row 3, yellow = editable team assumption). Counts people, not hours.").font = BOLD
    # (label, role, seniority or None, default minimum)
    checks = [
        ("Managers", "Manager", None, 1),
        ("Senior chefs", "Chef", "Senior", 1),
        ("All chefs", "Chef", None, 2),
        ("Kitchen porters", "Kitchen Porter", None, 1),
        ("Bartenders", "Bartender", None, 1),
        ("Servers", "Server", None, 2),
        ("Hosts", "Host", None, 0),
    ]
    header(ws, 2, ["date", "block"] + [c[0] for c in checks] + ["Status"],
           [13, 8] + [12] * len(checks) + [13])
    put(ws, 3, 1, "Minimum", BOLD)
    put(ws, 3, 2, None)
    for j, chk in enumerate(checks, start=3):
        put(ws, 3, j, chk[3], BLUE, fill=INPUT_FILL)
    rng = "Availability!${c}$2:${c}$" + str(avail_last)
    C, D, E, G, K = (rng.format(c=x) for x in "CDEGK")
    r = 4
    for d in dates:
        for block in ("AM", "PM"):
            put(ws, r, 1, d, BLUE, "ddd dd-mmm")
            put(ws, r, 2, block, BLUE)
            for j, (_, role, level, _) in enumerate(checks, start=3):
                f = f'=COUNTIFS({E},$A{r},{G},$B{r},{K},1,{C},"{role}"'
                f += f',{D},"{level}")' if level else ")"
                put(ws, r, j, f, GREEN, "0")
            tests = ",".join(f"{get_column_letter(j)}{r}<{get_column_letter(j)}$3"
                             for j in range(3, 3 + len(checks)))
            put(ws, r, 3 + len(checks), f'=IF(OR({tests}),"SHORTFALL","OK")')
            r += 1
    last = r - 1
    data_area = f"C4:{get_column_letter(2 + len(checks))}{last}"
    ws.conditional_formatting.add(data_area, FormulaRule(formula=["C4<C$3"], fill=RED_FILL))
    status = f"{get_column_letter(3 + len(checks))}4:{get_column_letter(3 + len(checks))}{last}"
    ws.conditional_formatting.add(status, CellIsRule(operator="equal", formula=['"SHORTFALL"'], fill=RED_FILL))
    ws.conditional_formatting.add(status, CellIsRule(operator="equal", formula=['"OK"'], fill=GREEN_FILL))
    s = get_column_letter(3 + len(checks))
    put(ws, last + 2, 1, "Blocks with a shortfall:", BOLD)
    put(ws, last + 2, 3, f'=COUNTIF({s}4:{s}{last},"SHORTFALL")', BOLD)
    ws.freeze_panes = "C4"


def main():
    staff = read_csv("staff.csv")
    blocks = read_csv("shift_blocks.csv")
    rows = read_csv("staff_availability_oct2026.csv")
    dates = sorted({date.fromisoformat(a["date"]) for a in rows})

    wb = Workbook()
    build_readme(wb)
    build_staff(wb, staff, len(rows))
    build_blocks(wb, blocks)
    build_rules(wb)
    avail_last = build_availability(wb, rows, len(staff))
    build_grid(wb, staff, dates, avail_last)
    build_coverage(wb, dates, avail_last)
    wb.calculation.fullCalcOnLoad = True
    wb.save(OUT_FILE)
    print(f"Wrote {OUT_FILE}")


if __name__ == "__main__":
    main()
